for path in sorted(glob.glob(str(ROOT / "bn" / "ch*.txt"))):
    raw = Path(path).read_text(encoding="utf-8")
    nl = "\r\n" if "\r\n" in raw else "\n"
    lines = raw.split(nl)
    out, i, changed = [], 0, False
    while i < len(lines):
        line = lines[i]
        if line.startswith("@") and line[1:].split("|")[0].isdigit() and int(line[1:].split("|")[0]) in NEW:
            n = int(line[1:].split("|")[0])
            j = i + 1
            while j < len(lines) and not lines[j].startswith("@") and not lines[j].startswith("CH|"):
                j += 1
            block = lines[i + 1 : j]
            spec = NEW[n]
            keep = {k: [b for b in block if b.startswith(k + "|")] for k in "ETNS"}
            new_block = []
            for key in "ETNS":
                if key in spec and spec[key] is None and key != "S":
                    continue  # drop this line
                if key in spec and spec[key] is not None:
                    values = spec[key] if isinstance(spec[key], list) else [spec[key]]
                    new_block += [f"{key}|{v}" for v in values]
                else:
                    new_block += keep[key]
            # blank or unknown lines are kept at the end
            rest = [b for b in block if b[:2] not in ("E|", "T|", "N|", "S|")]
            out += [line] + new_block + rest
            i, changed = j, True
            continue
        out.append(line)
        i += 1
    if changed:
        Path(path).write_text(nl.join(out), encoding="utf-8")
        print("updated", path)
